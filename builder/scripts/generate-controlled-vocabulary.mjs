import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { DEFAULT_VOCABULARY_REGISTRY } from "../lib/vocabulary-registry.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = path.resolve(path.dirname(scriptPath), "../..");
const schemaId =
  "https://tiangong-lca.org/schemas/pcr/v1/controlled-vocabulary.schema.json";

const OUTPUTS = {
  module: path.join(
    repoRoot,
    "packages/pcr-core/src/generated/controlled-vocabulary.mjs",
  ),
  schema: path.join(
    repoRoot,
    "packages/pcr-core/schemas/controlled-vocabulary.schema.json",
  ),
};

function constantName(name) {
  return `${name.toUpperCase()}_VALUES`;
}

export function buildControlledVocabularyArtifacts({
  registry = DEFAULT_VOCABULARY_REGISTRY,
} = {}) {
  const vocabularies = Object.fromEntries(
    registry.ids.map((vocabulary) => [vocabulary, registry.values(vocabulary)]),
  );

  const moduleLines = [
    "// Generated by builder/scripts/generate-controlled-vocabulary.mjs.",
    "// Do not edit this file directly; edit builder/vocab/*.yaml and run npm run vocab:generate.",
    "",
  ];
  for (const [name, values] of Object.entries(vocabularies)) {
    moduleLines.push(
      `export const ${constantName(name)} = Object.freeze(${JSON.stringify(values)});`,
    );
  }
  moduleLines.push("", "export const CONTROLLED_VOCABULARY = Object.freeze({");
  for (const name of Object.keys(vocabularies)) {
    moduleLines.push(`  ${name}: ${constantName(name)},`);
  }
  moduleLines.push("});", "");

  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: schemaId,
    title: "TianGong PCR controlled vocabulary",
    $defs: Object.fromEntries(
      Object.entries(vocabularies).map(([name, values]) => [
        name,
        { type: "string", enum: values },
      ]),
    ),
  };

  return {
    [OUTPUTS.module]: `${moduleLines.join("\n")}\n`,
    [OUTPUTS.schema]: `${JSON.stringify(schema, null, 2)}\n`,
  };
}

export function generateControlledVocabulary({ check = false } = {}) {
  const artifacts = buildControlledVocabularyArtifacts();
  const stale = [];
  for (const [filePath, content] of Object.entries(artifacts)) {
    if (check) {
      if (!existsSync(filePath) || readFileSync(filePath, "utf8") !== content) {
        stale.push(path.relative(repoRoot, filePath).replaceAll(path.sep, "/"));
      }
      continue;
    }
    mkdirSync(path.dirname(filePath), { recursive: true });
    writeFileSync(filePath, content);
  }

  if (stale.length > 0) {
    throw new Error(
      [
        "Generated controlled vocabulary artifacts are stale:",
        ...stale.map((filePath) => `- ${filePath}`),
        "",
        "Next: run `npm run vocab:generate` and commit the generated files.",
      ].join("\n"),
    );
  }

  return Object.keys(artifacts).map((filePath) =>
    path.relative(repoRoot, filePath).replaceAll(path.sep, "/"),
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  const check = process.argv.slice(2).includes("--check");
  try {
    const files = generateControlledVocabulary({ check });
    process.stdout.write(
      check
        ? `Controlled vocabulary artifacts are current (${files.length}).\n`
        : `Generated controlled vocabulary artifacts:\n${files.map((file) => `- ${file}`).join("\n")}\n`,
    );
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
