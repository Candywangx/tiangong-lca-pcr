import {
  cpSync,
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  realpathSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { buildGuidance, listPcrs, readPcrMarkdown } from "../../pcr-core/src/index.mjs";

const repoRoot = path.resolve(fileURLToPath(new URL("../../..", import.meta.url)));
const packageRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const defaultOutDir = path.join(packageRoot, "dist");
const staticDir = path.join(packageRoot, "static");
const languages = ["en-US", "zh-CN"];
export const VIEWER_BUILD_MARKER = ".tiangong-pcr-viewer-build";

export function buildViewer({ root = repoRoot, outDir = defaultOutDir } = {}) {
  const resolvedRoot = canonicalizeExistingAncestors(root);
  const requestedOutDir = path.resolve(outDir);
  rejectOutputSymlink(requestedOutDir);
  const resolvedOutDir = canonicalizeExistingAncestors(requestedOutDir);
  assertSafeOutDir({ root: resolvedRoot, outDir: resolvedOutDir, requestedOutDir });

  const data = buildViewerData({ root: resolvedRoot });
  if (data.pcr_count === 0) {
    throw new Error(`Refusing to replace viewer output with an empty PCR catalog from ${resolvedRoot}`);
  }
  const parentDir = path.dirname(resolvedOutDir);
  mkdirSync(parentDir, { recursive: true });
  const tempDir = mkdtempSync(path.join(parentDir, `.${path.basename(resolvedOutDir)}-build-`));

  try {
    cpSync(staticDir, tempDir, { recursive: true });

    const dataDir = path.join(tempDir, "data");
    mkdirSync(dataDir, { recursive: true });
    writeFileSync(path.join(dataDir, "pcr-viewer-data.json"), `${JSON.stringify(data, null, 2)}\n`);
    writeFileSync(
      path.join(tempDir, VIEWER_BUILD_MARKER),
      "Generated by packages/pcr-viewer/scripts/build-viewer-data.mjs.\n",
    );
    replaceBuiltDirectory(tempDir, resolvedOutDir);
  } catch (error) {
    rmSync(tempDir, { recursive: true, force: true });
    throw error;
  }

  return data;
}

function assertSafeOutDir({ root, outDir, requestedOutDir }) {
  const filesystemRoot = path.parse(outDir).root;
  const canonicalRepoRoot = realpathSync(repoRoot);
  const canonicalPackageRoot = realpathSync(packageRoot);
  const canonicalStaticDir = realpathSync(staticDir);
  const canonicalDefaultOutDir = canonicalizeExistingAncestors(defaultOutDir);
  const protectedPaths = [filesystemRoot, root, canonicalRepoRoot, canonicalPackageRoot];
  if (protectedPaths.some((protectedPath) => outDir === protectedPath || isAncestor(outDir, protectedPath))) {
    throw new Error(`Refusing to build the PCR viewer into protected path: ${outDir}`);
  }
  if (outDir === canonicalStaticDir || isAncestor(canonicalStaticDir, outDir)) {
    throw new Error(`Refusing to build the PCR viewer inside its static source directory: ${outDir}`);
  }
  if (!existsSync(requestedOutDir)) {
    return;
  }
  const stat = lstatSync(requestedOutDir);
  if (!stat.isDirectory()) {
    throw new Error(`Viewer output path must be a real directory: ${outDir}`);
  }
  const entries = readdirSync(outDir);
  const isKnownGeneratedDirectory =
    outDir === canonicalDefaultOutDir || entries.includes(VIEWER_BUILD_MARKER);
  if (entries.length > 0 && !isKnownGeneratedDirectory) {
    throw new Error(
      `Refusing to replace non-empty directory without ${VIEWER_BUILD_MARKER}: ${outDir}`,
    );
  }
}

function rejectOutputSymlink(outDir) {
  try {
    if (lstatSync(outDir).isSymbolicLink()) {
      throw new Error(`Viewer output path must be a real directory: ${outDir}`);
    }
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }
}

function canonicalizeExistingAncestors(inputPath) {
  const suffix = [];
  let currentPath = path.resolve(inputPath);

  while (!existsSync(currentPath)) {
    const parentPath = path.dirname(currentPath);
    if (parentPath === currentPath) {
      throw new Error(`Unable to resolve an existing ancestor for path: ${inputPath}`);
    }
    suffix.unshift(path.basename(currentPath));
    currentPath = parentPath;
  }

  return path.join(realpathSync(currentPath), ...suffix);
}

function isAncestor(candidate, target) {
  return target.startsWith(`${candidate}${path.sep}`);
}

function replaceBuiltDirectory(tempDir, outDir) {
  if (!existsSync(outDir)) {
    renameSync(tempDir, outDir);
    return;
  }

  const backupDir = unusedSiblingPath(`${outDir}.previous`);
  renameSync(outDir, backupDir);
  try {
    renameSync(tempDir, outDir);
  } catch (error) {
    renameSync(backupDir, outDir);
    throw error;
  }
  rmSync(backupDir, { recursive: true, force: true });
}

function unusedSiblingPath(prefix) {
  let candidate = `${prefix}-${process.pid}`;
  let suffix = 0;
  while (existsSync(candidate)) {
    suffix += 1;
    candidate = `${prefix}-${process.pid}-${suffix}`;
  }
  return candidate;
}

export function buildViewerData({ root = repoRoot } = {}) {
  const pcrs = listPcrs({ root }).map((pcr) => {
    const markdown = Object.fromEntries(
      languages.map((language) => [language, readOptionalMarkdown({ root, pcr, language })]),
    );
    const guidance = readOptionalGuidance({ root, pcr });
    const classificationText = (pcr.classification_refs ?? [])
      .map((ref) => `${ref.system ?? ""} ${ref.version ?? ""} ${ref.code ?? ""} ${ref.title ?? ""}`)
      .join(" ");

    return {
      ...pcr,
      markdown,
      guidance,
      search_text: [
        pcr.id,
        pcr.path,
        pcr.title?.["en-US"],
        pcr.title?.["zh-CN"],
        pcr.status,
        pcr.content_maturity,
        pcr.readiness?.status,
        classificationText,
      ]
        .filter(Boolean)
        .join(" "),
    };
  });

  return {
    schema_version: 1,
    viewer_kind: "tiangong-pcr-static-viewer-data",
    generated_at_utc: new Date().toISOString(),
    pcr_count: pcrs.length,
    pcrs,
  };
}

function readOptionalMarkdown({ root, pcr, language }) {
  try {
    return readPcrMarkdown({ root, pcrId: pcr.id, language });
  } catch {
    return "";
  }
}

function readOptionalGuidance({ root, pcr }) {
  try {
    return buildGuidance({ root, pcrId: pcr.id });
  } catch (error) {
    return { guidance_error: error.message };
  }
}

function cliOptions(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--root") {
      options.root = path.resolve(requiredOptionValue(argv, index, token));
      index += 1;
    } else if (token === "--out-dir") {
      options.outDir = path.resolve(requiredOptionValue(argv, index, token));
      index += 1;
    } else {
      throw new Error(`Unknown option: ${token}`);
    }
  }
  return options;
}

function requiredOptionValue(argv, index, option) {
  const value = argv[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`Missing value for ${option}`);
  }
  return value;
}

if (isCliMain(import.meta.url)) {
  const data = buildViewer(cliOptions(process.argv.slice(2)));
  console.log(`Built PCR viewer data for ${data.pcr_count} PCR records.`);
}

function isCliMain(moduleUrl) {
  return (
    Boolean(process.argv[1]) &&
    canonicalCliPath(fileURLToPath(moduleUrl)) === canonicalCliPath(process.argv[1])
  );
}

function canonicalCliPath(value) {
  const resolved = path.resolve(value);
  try {
    return realpathSync(resolved);
  } catch (error) {
    if (error?.code === "ENOENT") {
      return resolved;
    }
    throw error;
  }
}
